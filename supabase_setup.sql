DROP POLICY IF EXISTS "Allow anon and auth inserts to registrations" ON public.registrations;
DROP POLICY IF EXISTS "Allow public anon inserts" ON public.registrations;
CREATE POLICY "Allow anon and auth inserts to registrations"
    ON public.registrations FOR INSERT
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read on registrations" ON public.registrations;
DROP POLICY IF EXISTS "Allow public anon reads" ON public.registrations;
CREATE POLICY "Allow public read on registrations"
    ON public.registrations FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Allow update own registration" ON public.registrations;
DROP POLICY IF EXISTS "Allow anon and auth update to registrations" ON public.registrations;
CREATE POLICY "Allow anon and auth update to registrations"
    ON public.registrations FOR UPDATE
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon and auth delete to registrations" ON public.registrations;
CREATE POLICY "Allow anon and auth delete to registrations"
    ON public.registrations FOR DELETE
    USING (true);

-- Profiles Policies: Allow read, insert, and update
DROP POLICY IF EXISTS "Public profiles are viewable by everyone" ON public.profiles;
DROP POLICY IF EXISTS "Allow public read on profiles" ON public.profiles;
CREATE POLICY "Allow public read on profiles"
    ON public.profiles FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Users can insert their own profile" ON public.profiles;
DROP POLICY IF EXISTS "Allow anon insert to profiles" ON public.profiles;
CREATE POLICY "Allow anon insert to profiles"
    ON public.profiles FOR INSERT
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update to profiles" ON public.profiles;
CREATE POLICY "Allow anon update to profiles"
    ON public.profiles FOR UPDATE
    USING (true)
    WITH CHECK (true);

-- Subjects, Materials & Bookmarks Policies
DROP POLICY IF EXISTS "Anyone can read subjects" ON public.subjects;
CREATE POLICY "Anyone can read subjects" ON public.subjects FOR SELECT USING (true);

DROP POLICY IF EXISTS "Anyone can read materials" ON public.materials;
CREATE POLICY "Anyone can read materials" ON public.materials FOR SELECT USING (true);

DROP POLICY IF EXISTS "Authenticated users can upload materials" ON public.materials;
CREATE POLICY "Authenticated users can upload materials" ON public.materials FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Users can manage own bookmarks" ON public.bookmarks;
CREATE POLICY "Users can manage own bookmarks" ON public.bookmarks FOR ALL USING (true);

DROP POLICY IF EXISTS "Users can manage own quiz history" ON public.quiz_history;
CREATE POLICY "Users can manage own quiz history" ON public.quiz_history FOR ALL USING (true);

-- ==============================================================================
-- 10. AUTO-SYNC TRIGGER: REGISTRATIONS -> PROFILES
-- When a user registers in registrations table, automatically syncs to profiles!
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.sync_registration_to_profile()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (
        id,
        name,
        email,
        role,
        branch,
        semester,
        roll_number,
        avatar_url,
        created_at,
        updated_at
    )
    VALUES (
        COALESCE(NEW.auth_user_id, NEW.id),
        NEW.name,
        NEW.email,
        NEW.role,
        COALESCE(NEW.branch, 'Computer Science'),
        COALESCE(NEW.semester, 1),
        COALESCE(NEW.roll_number, ''),
        COALESCE(NEW.avatar_url, ''),
        NEW.created_at,
        NEW.updated_at
    )
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name,
        email = EXCLUDED.email,
        role = EXCLUDED.role,
        branch = EXCLUDED.branch,
        semester = EXCLUDED.semester,
        roll_number = EXCLUDED.roll_number,
        updated_at = NOW();

    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_registration_to_profile ON public.registrations;
CREATE TRIGGER trg_sync_registration_to_profile
    AFTER INSERT OR UPDATE ON public.registrations
    FOR EACH ROW EXECUTE FUNCTION public.sync_registration_to_profile();

-- ==============================================================================
-- 11. AUTO-TRIGGER FROM SUPABASE AUTH (auth.users)
-- Syncs user credentials from Supabase Auth into both registrations & profiles
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.registrations (
        auth_user_id,
        name,
        email,
        role,
        branch,
        semester,
        roll_number,
        created_at,
        updated_at
    )
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'role', 'student'),
        COALESCE(NEW.raw_user_meta_data->>'branch', 'Computer Science'),
        COALESCE((NEW.raw_user_meta_data->>'semester')::integer, 1),
        COALESCE(NEW.raw_user_meta_data->>'roll_number', ''),
        NOW(),
        NOW()
    )
    ON CONFLICT (email) DO UPDATE SET
        auth_user_id = EXCLUDED.auth_user_id,
        name = EXCLUDED.name,
        role = EXCLUDED.role,
        branch = EXCLUDED.branch,
        semester = EXCLUDED.semester,
        roll_number = EXCLUDED.roll_number,
        updated_at = NOW();

    INSERT INTO public.profiles (
        id,
        name,
        email,
        role,
        branch,
        semester,
        roll_number,
        created_at,
        updated_at
    )
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'role', 'student'),
        COALESCE(NEW.raw_user_meta_data->>'branch', 'Computer Science'),
        COALESCE((NEW.raw_user_meta_data->>'semester')::integer, 1),
        COALESCE(NEW.raw_user_meta_data->>'roll_number', ''),
        NOW(),
        NOW()
    )
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name,
        role = EXCLUDED.role,
        branch = EXCLUDED.branch,
        semester = EXCLUDED.semester,
        roll_number = EXCLUDED.roll_number,
        updated_at = NOW();

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

-- ==============================================================================
