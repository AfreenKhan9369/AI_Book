FROM public.registrations
ON CONFLICT (id) DO UPDATE SET
    name = EXCLUDED.name,
    email = EXCLUDED.email,
    role = EXCLUDED.role,
    branch = EXCLUDED.branch,
    semester = EXCLUDED.semester,
    roll_number = EXCLUDED.roll_number;

